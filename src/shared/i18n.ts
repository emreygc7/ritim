const dicts: Record<Lang, Dict> = { en, tr }

export function translator(lang: Lang) {
  const d = dicts[lang]
  const t = (key: Key, vars?: Record<string, string | number>): string => {
    let s = d[key] as string
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
  const pct = (n: number): string => (lang === 'tr' ? `%${n}` : `${n}%`)
  return Object.assign(t, { dayShort: d['day.short'], dayLong: d['day.long'], pct })
}

export type T = ReturnType<typeof translator>

export function detectLang(locale: string): Lang {
  return locale.toLowerCase().startsWith('tr') ? 'tr' : 'en'
}
